"""Installing the package scripts and the generated package metadata."""

from __future__ import annotations

import re
import shlex
import shutil
from pathlib import Path

from .errors import ToolError
from .log import Log

REQUIRED_SCRIPTS = ("common.sh", "flash.sh", "flash-safe.sh", "fix-oem.sh")


def copy_scripts(scripts_dir: Path, out: Path, log: Log) -> list[str]:
    if not scripts_dir.is_dir():
        raise ToolError(f"scripts directory not found: {scripts_dir}")
    sources = sorted(scripts_dir.glob("*.sh"))
    if not sources:
        raise ToolError(f"no *.sh files in {scripts_dir}")
    names = {source.name for source in sources}
    for required in REQUIRED_SCRIPTS:
        if required not in names:
            raise ToolError(f"missing script template: {scripts_dir / required}")
    copied: list[str] = []
    for source in sources:
        destination = out / source.name
        shutil.copy2(source, destination)
        destination.chmod(0o755)
        copied.append(source.name)
        log(f"  {source.name} <- scripts/{source.name}")
    return copied


def write_package_env(
    out: Path,
    props: dict[str, str],
    model_regex: str,
    oem_name: str,
    log: Log,
) -> None:
    title = props.get("post-version") or out.name
    identity = "" if oem_name == "none" else oem_name
    lines = [
        "# Generated by ota2fastboot.py. Do not edit by hand.",
        f"PACKAGE_TITLE={shlex.quote(title)}",
        f"PACKAGE_VERSION={shlex.quote(props.get('post-version', ''))}",
        f"MODEL_REGEX={shlex.quote(model_regex)}",
        f"OEM_IDENTITY={shlex.quote(identity)}",
        "",
    ]
    path = out / "package.env"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log(f"  package.env: {title}")


def check_script_contract(out: Path, log: Log) -> None:
    optional_missing: list[str] = []
    checked = 0
    for name in ("flash.sh", "flash-safe.sh"):
        script = out / name
        if not script.is_file():
            raise ToolError(f"missing generated script: {name}")
        text = script.read_text(encoding="utf-8")
        for match in re.finditer(
            r'"([a-z0-9_-]+)\|(firmware-update/[^"|]+)(?:\|(optional))?"', text
        ):
            relative = match.group(2)
            optional = match.group(3) == "optional"
            checked += 1
            if not (out / relative).is_file():
                if optional:
                    optional_missing.append(relative)
                else:
                    raise ToolError(f"{name} requires a missing file: {relative}")

    if not (out / "common.sh").is_file():
        raise ToolError("common.sh missing (flash.sh sources it)")

    oem_images = list((out / "firmware-update" / "oem").glob("OEM_*.img"))
    log(
        f"script contract: {checked} image references ok, "
        f"{len(oem_images)} OEM variants present"
    )
    if optional_missing:
        log(
            "  optional images not packaged: "
            + ", ".join(sorted(set(optional_missing)))
        )
